type EventInput = Omit<HistoricalEvent, "periodId" | "participants" | "sources"> & {
  pages: string;
  participants: [personId: string, role: string][];
};
const defineEvent = ({ pages, participants, ...event }: EventInput): HistoricalEvent => {
  const source = bookSource(pages, event.title);
  return {
    ...event, periodId: "rashidun", sources: [source],
    participants: participants.map(([personId, role], index) => ({
      personId, role, sortOrder: index * 10, sources: [source],
    })),
  };
};

